# -*- coding: utf-8 -*-
"""可注入的時鐘。

用途: 讓「過期 29 秒 vs 31 秒」「登入 300 秒後」這類邊界行為可被測試控制。
副作用: 無。

🔴 為什麼不直接呼叫 `time.time()`:
   契約 §3.3 的兩個要求——±30 秒時鐘容忍、access token 300 秒後主動續期
   ——**都只在時間邊界上出錯**。用真實時鐘寫的測試要嘛得 `sleep(301)`
   (沒人會跑),要嘛只能斷言「大概對」(等於沒斷言)。
   把時鐘拉成參數,是這兩條紅線唯一能被自動驗證的形狀。
"""

import time


def now() -> float:
    """回傳當前 epoch 秒(浮點)。

    回傳: float
    副作用: 無
    """
    return time.time()
