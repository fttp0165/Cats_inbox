#!/usr/bin/env bash
# =============================================================================
# run_all.sh — 跑 tests/ 下全部 test_*.sh(CI 與本機共用同一入口)
# 為什麼:第三條2 要求測試納入 CI;單一入口讓 CI 設定永遠不必跟著測試清單改。
# =============================================================================
set -u
cd "$(dirname "$0")"
TOTAL=0
FAILED=0
for t in test_*.sh; do
  [ -e "$t" ] || continue
  TOTAL=$((TOTAL+1))
  echo "=========================================="
  echo "▶ $t"
  echo "=========================================="
  if bash "$t"; then
    echo "▶ $t 通過"
  else
    echo "▶ $t 失敗"
    FAILED=$((FAILED+1))
  fi
done
echo "=========================================="
echo "測試檔: $((TOTAL-FAILED))/${TOTAL} 通過"
[ "$FAILED" -eq 0 ] || exit 1
